package com.pi2.anchor.sdk.model;

/**
 * Minimal stub satisfying the ApiClient.valueToString() reference generated
 * by openapi-generator in each model's toUrlQueryString() helper method.
 * The full ApiClient (HTTP transport) lives in each SDK module separately.
 */
public class ApiClient {

    public static String valueToString(Object value) {
        if (value == null) {
            return "";
        }
        return value.toString();
    }
}
